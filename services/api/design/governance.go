func governanceService() {
	Security(SessionCookie)
	for _, code := range []string{"unauthenticated", "forbidden", "invalid", "conflict", "not_found", "internal", "unavailable"} {
		Error(code, IAMProblem)
	}
	HTTP(func() {
		Response("unauthenticated", StatusUnauthorized)
		Response("forbidden", StatusForbidden)
		Response("invalid", StatusBadRequest)
		Response("conflict", StatusConflict)
		Response("not_found", StatusNotFound)
		Response("internal", StatusInternalServerError)
		Response("unavailable", StatusServiceUnavailable)
	})
}
func targetQuery() {
	Attribute("targetKind", String, func() { Enum("workspace"); Default("workspace") })
	Attribute("targetId", Int64, func() { Minimum(0); Maximum(0); Default(0) })
}
func targetParams() { Param("targetKind"); Param("targetId") }
func resourceId()   { Attribute("id", Int64, func() { Minimum(1) }); Required("id") }
func publicationFields() {
	Attribute("baseRevision", Int64, func() { Minimum(0) })
	Attribute("proof", String)
	Required("baseRevision", "proof")
}
func reasonField() {
	Attribute("reason", String, func() { MinLength(5); MaxLength(500) })
	Required("reason")
}


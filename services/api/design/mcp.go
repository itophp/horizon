package design

import . "goa.design/goa/v3/dsl"

var MCPToken = Type("MCPToken", func() {
	Attribute("id", Int64)
	Attribute("departmentId", Int64)
	Attribute("name", String)
	Attribute("prefix", String)
	Attribute("tools", ArrayOf(String))
	Attribute("createdAt", String)
	Attribute("expiresAt", String)
	Attribute("revokedAt", String)
	Attribute("lastUsedAt", String)
	Attribute("revokedBy", Int64)
	Required("id", "departmentId", "name", "prefix", "tools", "createdAt", "expiresAt", "revokedAt", "lastUsedAt", "revokedBy")
})
var MCPTokenCreated = Type("MCPTokenCreated", func() {
	Attribute("token", MCPToken)
	Attribute("secret", String)
	Required("token", "secret")
})
var MCPAudit = Type("MCPAudit", func() {
	Attribute("id", Int64)
	Attribute("tokenId", Int64)
	Attribute("departmentId", Int64)
	Attribute("tool", String)
	Attribute("resultCode", String)
	Attribute("durationMs", Int64)
	Attribute("requestId", String)
	Attribute("createdAt", String)
	Required("id", "tokenId", "departmentId", "tool", "resultCode", "durationMs", "requestId", "createdAt")
})
var _ = Service("mcp_management", func() {
	Security(SessionCookie)
	Error("unauthenticated", IAMProblem)
	Error("forbidden", IAMProblem)
	Error("not_found", IAMProblem)
	Error("invalid", IAMProblem)
	Error("unavailable", IAMProblem)
	Error("internal", IAMProblem)
	HTTP(func() {
		Header("cookie:Cookie")
		Response("unauthenticated", StatusUnauthorized)
		Response("forbidden", StatusForbidden)
		Response("not_found", StatusNotFound)
		Response("invalid", StatusBadRequest)
		Response("unavailable", StatusServiceUnavailable)
		Response("internal", StatusInternalServerError)
	})
	Method("create", func() {
		Payload(func() {
			cookiePayload()
			Attribute("password", String, func() { MinLength(1); MaxLength(128) })
			Required("password")
			Attribute("name", String, func() { MinLength(1); MaxLength(100) })
			Attribute("departmentId", Int64, func() { Minimum(1) })
			Attribute("days", Int, func() { Minimum(1); Maximum(90); Default(30) })
			Attribute("tools", ArrayOf(String), func() { MinLength(1); MaxLength(10) })
			Required("name", "departmentId", "tools")
		})
		Result(MCPTokenCreated)
		HTTP(func() { POST("/api/auth/mcp/tokens"); Response(StatusCreated) })
	})
	Method("list", func() {
		Payload(func() { cookiePayload() })
		Result(ArrayOf(MCPToken))
		HTTP(func() { GET("/api/auth/mcp/tokens"); Response(StatusOK) })
	})
	Method("revoke", func() {
		Payload(func() {
			cookiePayload()
			Attribute("password", String, func() { MinLength(1); MaxLength(128) })
			Attribute("id", Int64, func() { Minimum(1) })
			Required("id", "password")
		})
		HTTP(func() { DELETE("/api/auth/mcp/tokens/{id}"); Response(StatusNoContent) })
	})
	Method("rotate", func() {
		Payload(func() {
			cookiePayload()
			Attribute("password", String, func() { MinLength(1); MaxLength(128) })
			Attribute("id", Int64, func() { Minimum(1) })
			Required("id", "password")
		})
		Result(MCPTokenCreated)
		HTTP(func() { POST("/api/auth/mcp/tokens/{id}/rotate"); Response(StatusCreated) })
	})
	Method("capabilities", func() {
		Payload(func() { cookiePayload(); Attribute("departmentId", Int64, func() { Minimum(1) }) })
		Result(ArrayOf(String))
		HTTP(func() { GET("/api/auth/mcp/capabilities"); Param("departmentId"); Response(StatusOK) })
	})
	Method("admin_revoke", func() {
		Payload(func() {
			cookiePayload()
			Attribute("password", String, func() { MinLength(1); MaxLength(128) })
			Attribute("id", Int64, func() { Minimum(1) })
			Required("password", "id")
		})
		HTTP(func() { DELETE("/api/admin/mcp/tokens/{id}"); Response(StatusNoContent) })
	})
	Method("audit", func() {
		Payload(func() { cookiePayload() })
		Result(ArrayOf(MCPAudit))
		HTTP(func() { GET("/api/auth/mcp/audit"); Response(StatusOK) })
	})
})

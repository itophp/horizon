package design

import . "goa.design/goa/v3/dsl"

// The capability service is the runtime face of the platform: one catalog, one
// invocation gateway, one audit trail and one approval queue shared by the React
// console, the agent, workflows and external adapters.

var CapabilityContract = Type("CapabilityContract", func() {
	Description("One registered business capability. The contract is machine readable and shared by every entry point.")
	Attribute("name", String, func() { MinLength(1); MaxLength(80) })
	Attribute("version", String, func() { MinLength(1); MaxLength(16) })
	Attribute("title", String, func() { MaxLength(120) })
	Attribute("description", String, func() { MaxLength(2000) })
	Attribute("domain", String, func() { MaxLength(40) })
	Attribute("entity", String, func() { MaxLength(40) })
	Attribute("permission", String, func() { MaxLength(80) })
	Attribute("risk", String, func() { Enum("low", "medium", "high", "critical") })
	Attribute("approval", String, func() { Enum("auto", "confirm", "four-eyes", "forbidden") })
	Attribute("idempotent", Boolean)
	Attribute("readOnly", Boolean)
	Attribute("executor", String, func() { MaxLength(80) })
	Attribute("layer", String, func() { Enum("atomic", "orchestration") })
	Attribute("kind", String, func() { Enum("service", "sql", "command", "external", "event") })
	Attribute("reads", ArrayOf(String))
	Attribute("writes", ArrayOf(String))
	Attribute("effect", String, func() { Enum("none", "compensable", "irreversible") })
	Attribute("retrySafe", Boolean)
	Attribute("tags", ArrayOf(String))
	Attribute("successEvents", ArrayOf(String))
	Attribute("inputSchema", Any)
	Attribute("outputSchema", Any)
	Required("name", "version", "title", "description", "domain", "entity", "permission", "risk", "approval", "idempotent", "readOnly", "executor", "tags", "successEvents", "inputSchema", "outputSchema")
})

var CapabilityInvocation = Type("CapabilityInvocation", func() {
	Description("One audited capability call. Input is the redacted projection; the digest binds replays.")
	Attribute("invocationId", String)
	Attribute("capability", String)
	Attribute("version", String)
	Attribute("origin", String, func() { Enum("human-ui", "agent", "workflow", "api", "event", "approval", "capability") })
	Attribute("status", String, func() { Enum("requested", "awaiting_approval", "executing", "succeeded", "failed", "cancelled") })
	Attribute("input", Any)
	Attribute("inputDigest", String)
	Attribute("result", Any)
	Attribute("errorCode", String)
	Attribute("approvalId", Int64)
	Attribute("correlationId", String)
	Attribute("causationId", String)
	Attribute("triggerDepth", Int)
	Attribute("durationMs", Int)
	Attribute("traceId", String)
	Attribute("createdAt", String)
	Attribute("finishedAt", String)
	Required("invocationId", "capability", "version", "origin", "status", "input", "inputDigest", "errorCode", "approvalId", "correlationId", "causationId", "triggerDepth", "durationMs", "traceId", "createdAt", "finishedAt")
})

var CapabilityResult = Type("CapabilityResult", func() {
	Description("Uniform invocation result. Business failures are reported in status/errorCode, not as transport errors.")
	Attribute("invocationId", String)
	Attribute("status", String, func() { Enum("requested", "awaiting_approval", "executing", "succeeded", "failed", "cancelled") })
	Attribute("data", Any)
	Attribute("eventIds", ArrayOf(String))
	Attribute("approvalId", Int64)
	Attribute("errorCode", String)
	Attribute("traceId", String)
	Attribute("replayed", Boolean)
	Required("invocationId", "status", "eventIds", "errorCode", "traceId", "replayed")
})

var CapabilityApproval = Type("CapabilityApproval", func() {
	Description("A confirmation card bound to the reviewed payload. Only allowlisted argument fields are projected.")
	Attribute("id", Int64)
	Attribute("invocationId", String)
	Attribute("capability", String)
	Attribute("version", String)
	Attribute("risk", String)
	Attribute("approval", String)
	Attribute("status", String, func() { Enum("pending", "approved", "rejected", "expired", "executed", "failed") })
	Attribute("arguments", Any)
	Attribute("requestedAt", String)
	Attribute("expiresAt", String)
	Attribute("decidedAt", String)
	Attribute("decisionNote", String)
	Attribute("executionCode", String)
	Attribute("mine", Boolean)
	Required("id", "invocationId", "capability", "version", "risk", "approval", "status", "arguments", "requestedAt", "expiresAt", "decidedAt", "decisionNote", "executionCode", "mine")
})

var CapabilityEvent = Type("CapabilityEvent", func() {
	Description("A business event with the outcome of its AI trigger, when a policy matched.")
	Attribute("eventId", String)
	Attribute("type", String)
	Attribute("aggregateType", String)
	Attribute("aggregateId", String)
	Attribute("payload", Any)
	Attribute("invocationId", String)
	Attribute("correlationId", String)
	Attribute("causationId", String)
	Attribute("depth", Int)
	Attribute("createdAt", String)
	Attribute("aiStatus", String)
	Attribute("aiPolicy", String)
	Attribute("aiRunId", Int64)
	Required("eventId", "type", "aggregateType", "aggregateId", "payload", "invocationId", "correlationId", "causationId", "depth", "createdAt", "aiStatus", "aiPolicy", "aiRunId")
})

var _ = Service("capability", func() {
	Description("Capability catalog, invocation gateway, audit trail, business events and human approvals.")
	Security(SessionCookie)
	Error("unauthenticated", IAMProblem)
	Error("forbidden", IAMProblem)
	Error("invalid", IAMProblem)
	Error("not_found", IAMProblem)
	Error("conflict", IAMProblem)
	Error("unavailable", IAMProblem)
	Error("internal", IAMProblem)
	HTTP(func() {
		Header("cookie:Cookie")
		Response("unauthenticated", StatusUnauthorized)
		Response("forbidden", StatusForbidden)
		Response("invalid", StatusBadRequest)
		Response("not_found", StatusNotFound)
		Response("conflict", StatusConflict)
		Response("unavailable", StatusServiceUnavailable)
		Response("internal", StatusInternalServerError)
	})
	Method("definitions", func() {
		Description("List the capabilities the caller may use, with their policy and contracts.")
		Payload(func() { cookiePayload() })
		Result(ArrayOf(CapabilityContract))
		HTTP(func() { GET("/api/capabilities"); Response(StatusOK) })
	})
	Method("invoke", func() {
		Description("Invoke one capability through the full gateway pipeline.")
		Payload(func() {
			cookiePayload()
			Attribute("name", String, func() { MinLength(1); MaxLength(80) })
			Attribute("version", String, func() { MaxLength(16) })
			Attribute("input", Any)
			Attribute("idempotencyKey", String, func() { MaxLength(120) })
			Attribute("correlationId", String, func() { MaxLength(120) })
			Attribute("causationId", String, func() { MaxLength(120) })
			Required("name", "input")
		})
		Result(CapabilityResult)
		HTTP(func() {
			POST("/api/capabilities/{name}/invocations")
			Response(StatusOK)
		})
	})
	Method("invocations", func() {
		Description("List the caller's own capability invocations, newest first.")
		Payload(func() {
			cookiePayload()
			Attribute("limit", Int, func() { Minimum(1); Maximum(100); Default(30) })
		})
		Result(ArrayOf(CapabilityInvocation))
		HTTP(func() { GET("/api/capabilities/invocations"); Param("limit"); Response(StatusOK) })
	})
	Method("invocation", func() {
		Description("Read one invocation owned by the caller.")
		Payload(func() {
			cookiePayload()
			Attribute("invocationId", String, func() { MinLength(1); MaxLength(120) })
			Required("invocationId")
		})
		Result(CapabilityInvocation)
		HTTP(func() { GET("/api/capabilities/invocations/{invocationId}"); Response(StatusOK) })
	})
	Method("approvals", func() {
		Description("List pending confirmations for the caller, or every pending card for a reviewer.")
		Payload(func() { cookiePayload() })
		Result(ArrayOf(CapabilityApproval))
		HTTP(func() { GET("/api/capabilities/approvals"); Response(StatusOK) })
	})
	Method("decide", func() {
		Description("Approve or reject a pending confirmation. Approval re-resolves the requester's authority.")
		Payload(func() {
			cookiePayload()
			Attribute("id", Int64, func() { Minimum(1) })
			Attribute("approve", Boolean)
			Attribute("note", String, func() { MaxLength(500) })
			Required("id", "approve")
		})
		Result(CapabilityResult)
		HTTP(func() { POST("/api/capabilities/approvals/{id}/decisions"); Response(StatusOK) })
	})
	Method("events", func() {
		Description("List business events the caller may see, with their AI trigger status.")
		Payload(func() {
			cookiePayload()
			Attribute("limit", Int, func() { Minimum(1); Maximum(100); Default(30) })
		})
		Result(ArrayOf(CapabilityEvent))
		HTTP(func() { GET("/api/capabilities/events"); Param("limit"); Response(StatusOK) })
	})
})

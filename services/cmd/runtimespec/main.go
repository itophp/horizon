// Command runtimespec generates structural TS/Zod contracts from Go. Semantic
// reference/type/permission checks are performed by the runtime catalog.
package main

import (
	"baseline/services/api/applications/articles"
	ar "baseline/services/api/kernel/applicationruntime"
	"baseline/services/api/kernel/capability/contracts"
	"baseline/services/api/runtime/app"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"
)

func main() {
	check := flag.Bool("check", false, "Validate the deployment catalog without writing generated files")
	file := flag.String("file", "", "Additional compiled contribution definitions to validate")
	flag.Parse()
	plugins := app.BuiltinPlugins(nil)
	entries := (app.CapabilityModules{Plugins: plugins}).Entries()
	defs := []contracts.Definition{}
	for _, entry := range entries {
		defs = append(defs, entry.Definition)
	}
	sources := append([]ar.ApplicationV2{articles.RuntimeApplication()}, plugins.Catalog.Applications...)
	if *file != "" {
		raw, err := os.ReadFile(*file)
		if err != nil {
			panic(err)
		}
		var extra []ar.ApplicationV2
		if err = json.Unmarshal(raw, &extra); err != nil {
			panic(err)
		}
		sources = append(sources, extra...)
	}
	applications, versions, err := ar.AssembleDeployment(sources, app.EntitiesWithPlugins(plugins), defs)
	if err != nil {
		panic(err)
	}
	if err = validateLabels(versions); err != nil {
		panic(err)
	}
	if *check {
		fmt.Println("Runtime contribution contracts valid:", len(versions))
		return
	}
	if err = os.MkdirAll("../docs/generated/runtime", 0755); err != nil {
		panic(err)
	}
	raw, err := json.MarshalIndent(applications, "", "  ")
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("../docs/generated/runtime/applications.json", append(raw, '\n'), 0644); err != nil {
		panic(err)
	}

	types := []reflect.Type{}
	seen := map[reflect.Type]bool{}
	var collect func(reflect.Type)
	collect = func(t reflect.Type) {
		if t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice {
			collect(t.Elem())
			return
		}
		if t.Kind() != reflect.Struct || seen[t] {
			return
		}
		seen[t] = true
		types = append(types, t)
		for i := 0; i < t.NumField(); i++ {
			collect(t.Field(i).Type)
		}
	}
	for _, v := range []any{ar.Field{}, ar.Relation{}, ar.Page{}, ar.Application{}, ar.ApplicationV2{}, ar.SemanticContext{}, ar.InstallationCatalog{}, ar.CompatibilityReport{}, ar.DefinitionView{}, ar.DefinitionList{}, ar.DefinitionChange{}, ar.DefinitionBaselineList{}, ar.DefinitionHistory{}, ar.DefinitionDiff{}, ar.DefinitionMergeReport{}, ar.DefinitionValidation{}} {
		collect(reflect.TypeOf(v))
	}
	out := "// Generated by cmd/runtimespec. Do not edit.\nimport { z } from \"zod\";\n"
	manifest, err := json.MarshalIndent(ar.DeploymentCandidates(versions), "", "  ")
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("../docs/generated/runtime/deployment.json", append(manifest, '\n'), 0644); err != nil {
		panic(err)
	}
	out += "export const runtimeDeploymentCandidates = " + string(manifest) + " as const;\n"
	for _, t := range types {
		out += "export interface Runtime" + t.Name() + " {\n"
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			optional := ""
			if len(tag) > 1 {
				optional = "?"
			}
			out += fmt.Sprintf("%s%s: %s;\n", tag[0], optional, ts(f.Type))
		}
		out += "}\n"
	}
	for _, t := range types {
		out += "export const runtime" + t.Name() + "Schema: z.ZodType<Runtime" + t.Name() + "> = z.object({"
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			out += tag[0] + ":" + zs(f.Type)
			if len(tag) > 1 {
				out += ".optional()"
			}
			out += ","
		}
		out += "}).strict();\n"
	}
	if err := os.WriteFile("../apps/web/src/api/generated/runtime.ts", []byte(out), 0644); err != nil {
		panic(err)
	}
}
func ts(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return ts(t.Elem())
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int64, reflect.Float64:
		return "number"
	case reflect.Slice:
		return ts(t.Elem()) + "[]"
	case reflect.Struct:
		return "Runtime" + t.Name()
	default:
		panic(t.String())
	}
}
func zs(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return zs(t.Elem())
	case reflect.String:
		return "z.string()"
	case reflect.Bool:
		return "z.boolean()"
	case reflect.Int, reflect.Int64:
		return "z.number().int()"
	case reflect.Float64:
		return "z.number()"
	case reflect.Slice:
		return "z.array(" + zs(t.Elem()) + ")"
	case reflect.Struct:
		return "z.lazy(()=>runtime" + t.Name() + "Schema)"
	default:
		panic(t.String())
	}
}
